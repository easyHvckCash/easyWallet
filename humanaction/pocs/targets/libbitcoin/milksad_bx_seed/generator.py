# Exact C++ std::mt19937 implementation (different from Python random module's MT19937!)
# Python random.seed(int) uses init_by_array, while C++ std::mt19937(uint32)
# uses simple init_genrand. Must implement manually to guarantee equivalence.

class MT19937:
    """Exact reproduction of C++ std::mt19937 (Knuth's init, 32-bit seed)"""

    def __init__(self, seed: int):
        self.mt = [0] * 624
        self.index = 624
        self.mt[0] = seed & 0xFFFFFFFF
        for i in range(1, 624):
            self.mt[i] = (1812433253 * (self.mt[i-1] ^ (self.mt[i-1] >> 30)) + i) & 0xFFFFFFFF

    def _twist(self):
        for i in range(624):
            y = (self.mt[i] & 0x80000000) | (self.mt[(i + 1) % 624] & 0x7FFFFFFF)
            self.mt[i] = self.mt[(i + 397) % 624] ^ (y >> 1)
            if y & 1:
                self.mt[i] ^= 0x9908B0DF
        self.index = 0

    def next(self) -> int:
        if self.index >= 624:
            self._twist()
        y = self.mt[self.index]
        y ^= (y >> 11)
        y ^= (y << 7) & 0x9D2C5680
        y ^= (y << 15) & 0xEFC60000
        y ^= (y >> 18)
        self.index += 1
        return y & 0xFFFFFFFF


def bx_seed_128(seed: int) -> bytes:
    """
    Exactly reproduce the output of libbitcoin bx seed 128.
    C++ code: generate(out.begin(), out.end(), [&]{ return next(); })
    where next() = get_twister()() (i.e. mt19937::operator()(), taking low 8 bits)

    Note: libbitcoin's pseudo_random::next() returns a full uint8_t:
    The actual implementation is uniform_int_distribution<uint8_t>(0, max_uint8)(twister)
    but for MT19937, uniform_int_distribution<uint8_t>(0,255) is equivalent to twister() & 0xFF
    (because 255 = 2^8-1, a power of 2 minus 1, no rejection sampling needed)
    """
    mt = MT19937(seed)
    return bytes([mt.next() & 0xFF for _ in range(16)])


def entropy_to_mnemonic_12(entropy_bytes: bytes) -> str:
    """BIP-39: 16 bytes (128 bit) -> 12-word mnemonic"""
    h = sha256(entropy_bytes).digest()
    b = int.from_bytes(entropy_bytes, 'big')
    checksum_bits = (h[0] >> 4) & 0x0F
    combined = (b << 4) | checksum_bits
    words = []
    for i in range(11, -1, -1):
        idx = (combined >> (i * 11)) & 0x7FF
        words.append(BIP39_WORDLIST[idx])
    return ' '.join(words)


